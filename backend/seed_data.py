async def seed_characters(db):
    """Insert official characters if they don't already exist."""
    coll = db.characters
    inserted = 0
    for char_data in OFFICIAL_CHARACTERS:
        existing = await coll.find_one({"name": char_data["name"], "owner_id": None})
        if existing:
            continue
        # Set defaults
        full = {**char_data}
        full.setdefault("owner_id", None)
        full.setdefault("status", "online")
        full.setdefault("is_custom", False)
        full.setdefault("is_public", True)
        full.setdefault("has_story", True)
        full.setdefault("has_live", True)
        full.setdefault("has_audio", True)
        full.setdefault("nsfw", True)
        char = CharacterModel(**full)
        doc = char.model_dump()
        doc["created_at"] = doc["created_at"].isoformat()
        await coll.insert_one(doc)
        inserted += 1
    return inserted
